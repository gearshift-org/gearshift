const FOLDER_ICONS: Record<string, string> = {
  app: folderSrcIcon,
  components: folderSrcIcon,
  lib: folderSrcIcon,
  src: folderSrcIcon,
  source: folderSrcIcon,
};

export function getFileIconUrl(fileName: string): string {
  const lower = fileName.toLowerCase();
  const byName = FILE_NAME_ICONS[lower];
  if (byName) return byName;

  if (!lower.includes(".")) return fileIcon;

  const parts = lower.split(".");
  for (let i = 1; i < parts.length; i++) {
    const ext = parts.slice(i).join(".");
    const byExt = EXTENSION_ICONS[ext];
    if (byExt) return byExt;
  }

  return fileIcon;
}

export function getFolderIconUrl(folderName: string, open: boolean): string {
  const named = FOLDER_ICONS[folderName.toLowerCase()];
  if (named) return named;
  return open ? folderOpenIcon : folderIcon;
}
